"""Prepare a local MLX-LM Mary adapter experiment bundle.

This module performs no training and no network access. It converts Mary Dataset
v1's approved chat-format SFT rows into the train/valid/test layout expected by
MLX-LM, writes a conservative LoRA/QLoRA config, and records exact base lineage
plus evaluation/stacking boundaries.

MaryBench stays held out. Ordinary chats, MemoryManager, relationship state and
provider traces remain excluded by MaryDatasetV1Exporter.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
from hashlib import sha256
import json
from pathlib import Path
from typing import Any

from .dataset_v1 import MaryDatasetV1Exporter
from .dataset_audit import MaryDatasetV1Auditor


@dataclass(frozen=True)
class MlxTrainingProfile:
    profile_id: str
    model: str
    upstream_base: str
    num_layers: int
    max_seq_length: int
    experiment_class: str = "development"
    minimum_train_examples: int = 8
    batch_size: int = 1
    grad_accumulation_steps: int = 4
    iters: int = 300
    learning_rate: float = 1e-5
    lora_rank: int = 8
    lora_scale: float = 16.0
    lora_dropout: float = 0.05
    grad_checkpoint: bool = True
    val_batches: int = 25
    steps_per_eval: int = 50
    save_every: int = 50

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


